/** Land dots as [lng, lat] pairs (degrees). */
export function landDots(): [number, number][] {
  const bytes = Uint8Array.from(atob(LAND), (c) => c.charCodeAt(0));
  const out: [number, number][] = [];
  for (let r = 0; r < DOT_ROWS; r++) {
    for (let c = 0; c < DOT_COLS; c++) {
      const i = r * DOT_COLS + c;
      if (bytes[i >> 3] & (0x80 >> (i & 7))) out.push([-180 + (c + 0.5) * DOT_STEP, DOT_LAT_TOP - r * DOT_STEP]);
    }
  }
  return out;
}
