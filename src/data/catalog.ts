// Curated catalog: destinations, attractions and tour packages.
//
// This file is the single source of sample content. It seeds PostgreSQL
// (prisma/seed.ts) and is also served directly when no database is reachable,
// so the 3D journey works on a fresh clone.
//
// Coordinates come from Wikipedia/Wikidata. Heights are metres above the
// WGS84 ellipsoid (ground elevation + local geoid offset) — the 3D engine
// refines them against Cesium World Terrain once it loads.
// Photos are hotlinked from Wikimedia Commons; `imageCredit` links to each
// file's page with author and licence. Hotels and prices are sample data.

import type { Attraction, Destination, ItineraryDay, Hotel } from "@/lib/types";

const commons = (hashPath: string, file: string) => ({
  imageUrl: `https://thumb.wikimedia.org/wikipedia/commons/thumb/${hashPath}/${file}/1280px-${file}`,
  imageCredit: `https://commons.wikimedia.org/wiki/File:${file}`,
});

const commonsOriginal = (hashPath: string, file: string) => ({
  imageUrl: `https://upload.wikimedia.org/wikipedia/commons/${hashPath}/${file}`,
  imageCredit: `https://commons.wikimedia.org/wiki/File:${file}`,
});

type A = Attraction;
type CatalogDestination = Destination & { sortOrder: number };

export interface CatalogPackage {
  slug: string;
  destinationSlug: string;
  name: string;
  summary: string;
  description: string;
  durationDays: number;
  priceInr: number;
  groupSize: string;
  pace: string;
  images: string[];
  highlights: string[];
  activities: string[];
  includes: string[];
  excludes: string[];
  hotel: Hotel;
  featured: boolean;
  itinerary: ItineraryDay[];
}

